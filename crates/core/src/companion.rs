//! In-game update notifications, ported from `wowup-addon.service.ts`.
//!
//! When the "Addon Update Notifications" addon (folder `WowUp`) is installed, WowUp writes a small
//! data addon, `wowup_data_addon`, listing addons with updates so the game can show them.

use std::path::Path;

use anyhow::Result;

use crate::models::Addon;

pub const WOWUP_ADDON_FOLDER_NAME: &str = "WowUp";
pub const WOWUP_DATA_ADDON_FOLDER_NAME: &str = "wowup_data_addon";
const ICON: &[u8] = include_bytes!("../assets/ldbicon.tga");

/// `11.0.2` -> `110002` (`toInterfaceVersion`).
pub fn to_interface_version(v: &str) -> String {
    if !v.contains('.') {
        return v.to_string();
    }
    let mut parts: Vec<u32> = v.split('.').map(|p| p.parse().unwrap_or(0)).collect();
    parts.resize(3, 0);
    format!("{}{:02}{:02}", parts[0], parts[1], parts[2])
}

fn lua_escape(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}

fn find_by_folder<'a>(addons: &'a [Addon], folder: &str) -> Option<&'a Addon> {
    addons.iter().find(|a| a.installed_folder_list.iter().any(|f| f == folder))
}

/// Write `wowup_data_addon` if the notifications addon is installed. Returns whether it wrote.
pub fn write_data_addon(addons_dir: &Path, addons: &[Addon]) -> Result<bool> {
    let Some(wowup) = find_by_folder(addons, WOWUP_ADDON_FOLDER_NAME) else { return Ok(false) };
    let updates: Vec<&Addon> = addons
        .iter()
        .filter(|a| !a.is_ignored && !a.auto_update_enabled && a.latest_version != a.installed_version)
        .collect();
    let dir = addons_dir.join(WOWUP_DATA_ADDON_FOLDER_NAME);
    std::fs::create_dir_all(&dir)?;
    let interface = to_interface_version(wowup.game_version.first().map(String::as_str).unwrap_or(""));
    let mut data = format!(
        "-- this file is autogenerated by WowUp (app) at {}\nWOWUP_DATA = {{}}\nWOWUP_DATA.icon = \"Interface/AddOns/wowup_data_addon/ldbicon\"\nWOWUP_DATA.addonManagerName = \"WowUp\"\nWOWUP_DATA.addonManagerColorRGB = {{232/255,205/255,134/255}}\nWOWUP_DATA.addonManagerNameSlashCommand = \"/wowup\"\nWOWUP_DATA.updateAddonsList = {{\n",
        chrono::Local::now().to_rfc2822()
    );
    for a in updates {
        data.push_str(&format!(
            "  [\"{}\"] = {{\"{}\", \"{}\"}},\n",
            lua_escape(&a.name),
            lua_escape(a.installed_version.as_deref().unwrap_or("")),
            lua_escape(a.latest_version.as_deref().unwrap_or(""))
        ));
    }
    data.push_str("}\n");
    let toc = format!(
        "## Interface: {interface}\n## Title: Addon Update Notifications (WowUp Data)\n## Notes: Contains the data for addon updates available in WowUp. This addon is automatically installed through WowUp when the Addon Update Notifications addon is installed.\n## Author: WowUp\n## Version: {}\n## DefaultState: enabled\n## RequiredDeps: {}\n## X-Website: https://wowup.io\n## X-AddonProvider: wowup-app\n\ndata.lua\n",
        wowup.installed_version.as_deref().unwrap_or(""),
        wowup.installed_folders.as_deref().unwrap_or(WOWUP_ADDON_FOLDER_NAME)
    );
    std::fs::write(dir.join("data.lua"), data)?;
    std::fs::write(dir.join("wowup_data_addon.toc"), toc)?;
    let icon = dir.join("ldbicon.tga");
    if !icon.exists() {
        std::fs::write(icon, ICON)?;
    }
    Ok(true)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn interface_versions() {
        assert_eq!(to_interface_version("11.0.2"), "110002");
        assert_eq!(to_interface_version("1.15.7"), "11507");
        assert_eq!(to_interface_version("110002"), "110002");
    }

    #[test]
    fn writes_only_when_notifier_installed() {
        let dir = tempfile::tempdir().unwrap();
        let mut a = Addon { name: "Foo".into(), installed_version: Some("1".into()), latest_version: Some("2".into()), ..Default::default() };
        assert!(!write_data_addon(dir.path(), std::slice::from_ref(&a)).unwrap());
        let w = Addon {
            name: "Addon Update Notifications".into(),
            installed_folder_list: vec!["WowUp".into()],
            installed_folders: Some("WowUp".into()),
            game_version: vec!["11.0.2".into()],
            installed_version: Some("3".into()),
            latest_version: Some("3".into()),
            ..Default::default()
        };
        a.is_ignored = false;
        assert!(write_data_addon(dir.path(), &[a, w]).unwrap());
        let data = std::fs::read_to_string(dir.path().join("wowup_data_addon/data.lua")).unwrap();
        assert!(data.contains("[\"Foo\"] = {\"1\", \"2\"}"));
        let toc = std::fs::read_to_string(dir.path().join("wowup_data_addon/wowup_data_addon.toc")).unwrap();
        assert!(toc.contains("## Interface: 110002"));
    }
}
