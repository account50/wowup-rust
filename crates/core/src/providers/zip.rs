//! Direct `.zip` URL installs, ported from `zip-provider.ts`.

use std::sync::Arc;

use async_trait::async_trait;
use chrono::Utc;

use super::{AddonProvider, Capabilities};
use crate::models::*;
use crate::net::Net;

pub struct ZipProvider {
    net: Arc<Net>,
}

impl ZipProvider {
    pub fn new(net: Arc<Net>) -> Self {
        Self { net }
    }

    async fn validate_content_type(&self, url: &url::Url) -> anyhow::Result<()> {
        let resp = self.net.client().head(url.as_str()).send().await?;
        let ct = resp
            .headers()
            .get(reqwest::header::CONTENT_TYPE)
            .and_then(|v| v.to_str().ok())
            .unwrap_or("")
            .to_string();
        // Upstream compares exactly; parameters such as `; charset=` are tolerated here.
        let base = ct.split(';').next().unwrap_or("").trim();
        if !matches!(base, "application/zip" | "application/x-zip-compressed" | "application/octet-stream") {
            anyhow::bail!("Invalid zip content type {ct}");
        }
        Ok(())
    }

    fn file_name(url: &url::Url) -> String {
        url.path_segments().and_then(|mut s| s.next_back().map(str::to_string)).unwrap_or_default()
    }

    fn result(url: &url::Url, author: String, folders: Vec<String>, version: String) -> AddonSearchResult {
        AddonSearchResult {
            author,
            download_count: Some(1),
            external_id: url.to_string(),
            external_url: url.origin().ascii_serialization(),
            name: Self::file_name(url),
            provider_name: PROVIDER_ZIP.into(),
            thumbnail_url: String::new(),
            files: vec![AddonSearchResultFile {
                external_id: None,
                channel_type: AddonChannelType::Stable,
                download_url: url.to_string(),
                folders,
                game_version: String::new(),
                version,
                release_date: Some(Utc::now()),
                dependencies: vec![],
                changelog: Some(String::new()),
                title: None,
                authors: None,
            }],
            ..Default::default()
        }
    }
}

#[async_trait]
impl AddonProvider for ZipProvider {
    fn name(&self) -> &'static str {
        PROVIDER_ZIP
    }

    fn capabilities(&self) -> Capabilities {
        Capabilities { allow_rescan: false, can_show_changelog: false, ..Default::default() }
    }

    fn is_valid_addon_uri(&self, url: &url::Url) -> bool {
        url.path().to_lowercase().ends_with(".zip")
    }

    async fn search_by_url(&self, url: &url::Url, _i: &WowInstallation) -> anyhow::Result<Option<AddonSearchResult>> {
        if !self.is_valid_addon_uri(url) {
            anyhow::bail!("Invalid zip URL {url}");
        }
        self.validate_content_type(url).await?;
        let name = Self::file_name(url);
        let no_ext = name.strip_suffix(".zip").unwrap_or(&name).to_string();
        Ok(Some(Self::result(url, url.host_str().unwrap_or("").to_string(), vec![no_ext.clone()], no_ext)))
    }

    async fn get_by_id(&self, id: &str, _i: &WowInstallation) -> anyhow::Result<Option<AddonSearchResult>> {
        let url = url::Url::parse(id)?;
        self.validate_content_type(&url).await?;
        let name = Self::file_name(&url);
        Ok(Some(Self::result(&url, String::new(), vec![], name)))
    }

    async fn get_description(&self, inst: &WowInstallation, external_id: &str) -> anyhow::Result<String> {
        let _ = (inst, external_id);
        // Description is generated by the addon service from the installed tocs (see `AddonService::describe`).
        Ok(String::new())
    }
}
